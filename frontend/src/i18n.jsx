const zhTwManualOverrides = dictionaries["zh-TW"];
dictionaries["zh-TW"] = Object.fromEntries(
  Object.entries(dictionaries["zh-CN"]).map(([key, value]) => [key, toTraditionalText(value)]),
);
dictionaries["zh-TW"] = {
  ...dictionaries["zh-TW"],
  ...Object.fromEntries(
    Object.entries(zhTwManualOverrides).map(([key, value]) => [key, toTraditionalText(value)]),
  ),
  languageKo: "韓語",
  languageZhCN: "簡體中文",
};

function assertCompleteTranslation(locale, dictionary) {
  const englishKeys = Object.keys(dictionaries.en);
  const missing = englishKeys.filter((key) => !Object.hasOwn(dictionary, key));
  const extra = Object.keys(dictionary).filter((key) => !Object.hasOwn(dictionaries.en, key));
  if (missing.length || extra.length) {
    throw new Error(
      `Translation key mismatch for ${locale}. Missing: ${missing.join(", ") || "none"}. Extra: ${extra.join(", ") || "none"}.`,
    );
  }
}

const japaneseDictionary = { ...dictionaries.ja, ...jaOverrides };
const koreanDictionary = { ...koOverrides };
assertCompleteTranslation("zh-CN", dictionaries["zh-CN"]);
assertCompleteTranslation("zh-TW", dictionaries["zh-TW"]);
assertCompleteTranslation("ja", japaneseDictionary);
assertCompleteTranslation("ko", koreanDictionary);
dictionaries.ja = japaneseDictionary;
dictionaries.ko = koreanDictionary;

const I18nContext = createContext(null);

function detectSystemLanguage() {
  const lang = (navigator.language || "en").toLowerCase();
  if (lang.startsWith("zh-tw") || lang.startsWith("zh-hk") || lang.startsWith("zh-mo")) return "zh-TW";
  if (lang.startsWith("zh")) return "zh-CN";
  if (lang.startsWith("ja")) return "ja";
  if (lang.startsWith("ko")) return "ko";
  return "en";
}

function resolveLanguage(selection) {
  return selection === "system" ? detectSystemLanguage() : selection;
}

export function I18nProvider({ children }) {
  const [languageSelection, setLanguageSelectionState] = useState(
    () => localStorage.getItem(STORAGE_KEY) || localStorage.getItem(LEGACY_STORAGE_KEY) || "system",
  );
  const locale = resolveLanguage(languageSelection);
  const dictionary = dictionaries[locale] || dictionaries.en;

  function setLanguageSelection(next) {
    setLanguageSelectionState(next);
    localStorage.setItem(STORAGE_KEY, next);
    localStorage.removeItem(LEGACY_STORAGE_KEY);
  }

  const value = useMemo(
    () => ({
      languageSelection,
      locale,
      setLanguageSelection,
      t: (key) => dictionary[key] || dictionaries.en[key] || key,
    }),
    [dictionary, languageSelection, locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
